"""Copies Corner's platform-neutral code from ../windows/src into Corner.Core/src.

The Windows app stays the single source of truth: this script reads its files, drops every WPF/WinForms type
(the Shell partials, the skin brushes, the tray and autostart code) and the WPF usings, and writes what is left.
Run it again whenever the Windows sources change. It never writes inside ../corner.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', '..', 'windows', 'src'))
OUT = os.path.normpath(os.path.join(HERE, '..', 'Corner.Core', 'src'))

FILES = ['Corner.cs', 'Energy.cs', 'Plan.cs', 'Need.cs', 'Stats.cs', 'Checks.cs', 'Onboard.cs']
DROP = {'Shell', 'T', 'Row', 'RimBorder', 'Backdrop', 'PillBorder', 'Program', 'Autostart'}
UI_USING = re.compile(r'^\s*using\s+(?:\w+\s*=\s*)?System\.(?:Windows|Drawing|Runtime\.InteropServices)\b.*$\n?', re.M)

def code_mask(s):
    """Same length as s, with strings, chars and comments blanked so braces in them are not counted."""
    out = list(s); i = 0; n = len(s)
    def blank(a, b):
        for k in range(a, b):
            if out[k] != '\n': out[k] = ' '
    while i < n:
        c = s[i]
        if s.startswith('//', i):
            j = s.find('\n', i); j = n if j < 0 else j; blank(i, j); i = j
        elif s.startswith('/*', i):
            j = s.find('*/', i + 2); j = n if j < 0 else j + 2; blank(i, j); i = j
        elif s.startswith('@"', i):
            j = i + 2
            while j < n:
                if s[j] == '"':
                    if j + 1 < n and s[j + 1] == '"': j += 2; continue
                    break
                j += 1
            blank(i, j + 1); i = j + 1
        elif c == '"' or c == "'":
            j = i + 1
            while j < n and s[j] != c:
                j += 2 if s[j] == chr(92) else 1
            blank(i, j + 1); i = j + 1
        else:
            i += 1
    return ''.join(out)

DECL = re.compile(r'^[ \t]*(?:\[[^\n]*\][ \t]*\n[ \t]*)*(?:(?:public|internal|static|partial|sealed|abstract)\s+)*(?:class|struct|enum|interface)\s+(\w+)', re.M)

def strip(text):
    m = code_mask(text)
    cuts = []
    depth = 0; i = 0
    # walk top-level (depth 1 = inside the namespace) declarations
    pos = 0
    while True:
        d = DECL.search(m, pos)
        if not d: break
        depth = m[:d.start()].count('{') - m[:d.start()].count('}')
        name = d.group(1)
        # find the body
        b = m.find('{', d.end()); k = b; lvl = 0
        while True:
            if m[k] == '{': lvl += 1
            elif m[k] == '}':
                lvl -= 1
                if lvl == 0: break
            k += 1
        end = k + 1
        if depth == 1 and name in DROP:
            start = d.start()
            # take the comment lines straight above the type with it
            lines_before = text[:start].split('\n')
            while len(lines_before) > 1 and lines_before[-2].strip().startswith('//'):
                lines_before.pop(-2)
            start = len('\n'.join(lines_before[:-1])) + 1 if len(lines_before) > 1 else 0
            if text[end:end + 1] == '\n': end += 1
            cuts.append((start, end))
        pos = end if depth == 1 else d.end()
    for a, b in reversed(cuts):
        text = text[:a] + text[b:]
    text = UI_USING.sub('', text)
    return re.sub(r'\n{3,}', '\n\n', text)

def main():
    os.makedirs(OUT, exist_ok=True)
    for f in FILES:
        with open(os.path.join(SRC, f), encoding='utf-8-sig') as fh: text = fh.read()
        body = strip(text)
        head = '// GENERATED by tools/sync_core.py from corner/src/' + f + ' - edit the Windows source, then re-run the script.\n'
        with open(os.path.join(OUT, f), 'w', encoding='utf-8', newline='\n') as fh: fh.write(head + body)
        print('%-12s %5d -> %5d lines' % (f, text.count('\n'), body.count('\n')))

if __name__ == '__main__':
    main()
